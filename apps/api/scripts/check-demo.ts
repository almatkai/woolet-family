// Integration checks use only a task-owned PostgreSQL Unix socket, never an app database.
import postgres from 'postgres';
import { drizzle } from 'drizzle-orm/postgres-js';
import { migrate } from 'drizzle-orm/postgres-js/migrator';
import { eq } from 'drizzle-orm';
import { userInfo } from 'node:os';
import assert from 'node:assert/strict';

const socket = process.env.DEMO_TEST_SOCKET;
if (!socket || !/^\/tmp\/woolet-demo-pg\.[A-Za-z0-9]+$/.test(socket)) throw new Error('DEMO_TEST_SOCKET must be the task-owned temporary PostgreSQL socket directory');
process.env.PGHOST = socket;
process.env.PGPORT = '55491';
process.env.PGUSER = userInfo().username;
process.env.DATABASE_URL = 'postgresql:///woolet_demo_test';
process.env.POSTHOG_API_KEY = '';
process.env.POSTHOG_HOST = '';
Object.assign(process.env, { DEMO_OWNER_USER_ID: 'user_demoOwner', DEMO_PARTNER_USER_ID: 'user_demoPartner', DEMO_CHILD_USER_ID: 'user_demoChild' });
const client = postgres({ host: socket, port: 55491, database: 'woolet_demo_test', username: userInfo().username, max: 4 });
try {
    const schema = await import('../src/db/schema');
    const db = drizzle(client, { schema });
    await migrate(db, { migrationsFolder: new URL('../drizzle', import.meta.url).pathname });
    console.log('PASS: full migration chain on a fresh database');
    await db.insert(schema.currencies).values(schema.DEFAULT_CURRENCIES).onConflictDoNothing();
    const { seedDemo } = await import('../src/lib/demo/seed');
    const actors = { owner: 'user_demoOwner', partner: 'user_demoPartner', child: 'user_demoChild' };
    const seeded = await seedDemo(db, actors, new Date('2026-11-15T12:00:00Z'));
    assert.equal(seeded.created, true);
    const again = await seedDemo(db, actors);
    assert.equal(again.created, false);
    const { householdRouter } = await import('../src/routers/household');
    const { router } = await import('../src/lib/trpc');
    const api = router({ household: householdRouter });
    const caller = (actor: keyof typeof actors) => api.createCaller({ db, userId: actors[actor], honoContext: {} as never }).household;
    const alex = caller('owner'), jordan = caller('partner'), maya = caller('child');
    const offers = await alex.purchaseProposals();
    assert.equal(offers.proposals.length, 1);
    const washer = offers.proposals[0];
    assert.equal(washer.amount, '1200.00');
    const balance = async () => (await db.query.familyWallets.findFirst({ where: eq(schema.familyWallets.id, washer.walletId) }))!.balance;
    assert.equal(await balance(), '2020.00');
    await assert.rejects(jordan.respondToPurchaseProposal({ proposalId: washer.id, action: 'approve' }));
    await assert.rejects(maya.respondToPurchaseProposal({ proposalId: washer.id, action: 'approve' }));
    const responses = await Promise.all([alex.respondToPurchaseProposal({ proposalId: washer.id, action: 'approve' }), alex.respondToPurchaseProposal({ proposalId: washer.id, action: 'approve' })]);
    assert.equal(responses.filter(result => result.alreadyDecided).length, 1);
    assert.equal(await balance(), '820.00');
    console.log('PASS: proposal does not spend, self/child rejection, concurrent approval debits once');
    const purchase = await jordan.addTransaction({ walletId: washer.walletId, type: 'expense', amount: '1300.00', date: '2026-11-15', today: '2026-11-15', description: 'Sample purchase' });
    assert.equal(purchase.approvalRequired, true);
    assert.equal(await balance(), '820.00');
    const proposalId = purchase.proposal!.id;
    await alex.respondToPurchaseProposal({ proposalId, action: 'counter', amount: '950.00' });
    await assert.rejects(alex.respondToPurchaseProposal({ proposalId, action: 'approve' }));
    await assert.rejects(jordan.respondToPurchaseProposal({ proposalId, action: 'approve' }));
    assert.equal(await balance(), '820.00');
    await alex.addTransaction({ walletId: washer.walletId, type: 'income', amount: '500.00', date: '2026-11-15', today: '2026-11-15' });
    await jordan.respondToPurchaseProposal({ proposalId, action: 'approve' });
    assert.equal(await balance(), '370.00');
    console.log('PASS: counter changes the turn; insufficient balance rolls back; funded approval succeeds');
    await alex.addTransaction({ walletId: washer.walletId, type: 'income', amount: '2000.00', date: '2026-11-15', today: '2026-11-15' });
    const exact = await jordan.addTransaction({ walletId: washer.walletId, type: 'expense', amount: '1000.00', date: '2026-11-15', today: '2026-11-15' });
    assert.equal(exact.approvalRequired, false);
    const above = await jordan.addTransaction({ walletId: washer.walletId, type: 'expense', amount: '1000.01', date: '2026-11-15', today: '2026-11-15' });
    assert.equal(above.approvalRequired, true);
    assert.equal(await balance(), '1370.00');
    console.log('PASS: exactly 1000 spends normally; 1000.01 requires approval');
    await db.update(schema.aiUsage).set({ questionCountLifetime: 49 }).where(eq(schema.aiUsage.userId, actors.owner));
    const { AiUsageService } = await import('../src/services/ai/ai-usage-service');
    const reservations = await Promise.allSettled(Array.from({ length: 4 }, () => AiUsageService.reserveDemoQuestion(actors.owner)));
    if (!reservations.some(result => result.status === 'fulfilled')) console.error(reservations.map(result => result.status === 'rejected' ? String(result.reason?.message || result.reason) : 'reserved'));
    assert.equal(reservations.filter(result => result.status === 'fulfilled').length, 1);
    const usage = await db.query.aiUsage.findFirst({ where: eq(schema.aiUsage.userId, actors.owner) });
    assert.equal(usage?.questionCountLifetime, 50);
    await seedDemo(db, actors);
    assert.equal((await db.query.aiUsage.findFirst({ where: eq(schema.aiUsage.userId, actors.owner) }))?.questionCountLifetime, 50);
    console.log('PASS: concurrent AI reservations stop at 50 and reseeding does not reset usage');
    const beforeDeletion = await alex.purchaseProposals();
    await db.delete(schema.users).where(eq(schema.users.id, actors.partner));
    const afterDeletion = await alex.purchaseProposals();
    assert.equal(afterDeletion.proposals.length, beforeDeletion.proposals.length);
    const abandoned = afterDeletion.proposals.find(proposal => proposal.status === 'pending');
    assert.ok(abandoned?.canDecline);
    await alex.respondToPurchaseProposal({ proposalId: abandoned.id, action: 'decline' });
    assert.equal(await balance(), '1370.00');
    console.log('PASS: deleting a former participant preserves approval history and abandoned proposals can close');
} catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
} finally {
    await client.end();
}
process.exit(process.exitCode ?? 0);
